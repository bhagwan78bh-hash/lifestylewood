          <div class="care-step-card">
            <div class="step-badge">Step 2</div>
            <h3>Humidity & Climate Guard</h3>
            <p>Wood is hygroscopic; it absorbs and loses moisture based on ambient relative humidity.</p>
            <div class="care-checklist">
              <span>✔ Keep indoor humidity between 40%–55%</span>
              <span>✔ Keep 3 feet away from radiators & vents</span>
              <span>✔ Use UV filtering window films against sun fade</span>
            </div>
          </div>

          <div class="care-step-card">
            <div class="step-badge">Step 3</div>
            <h3>Bi-Annual Natural Waxing</h3>
