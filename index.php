            <h3 class="rule-title">The 70 / 20 / 10 Tonal Formula</h3>
            <p class="rule-desc">Never match every piece of wood identical in grain and stain — doing so results in a flat, showroom look. Instead:</p>
            <ul class="rule-points">
              <li><strong>70% Dominant Tone:</strong> Flooring or key cabinet color (e.g. natural oak).</li>
              <li><strong>20% Secondary Contrast:</strong> Anchor furniture (e.g. walnut dining table).</li>
              <li><strong>10% Accent Statement:</strong> Sculptural accessories (e.g. blackened ash bowls).</li>
            </ul>
          </div>

          <div class="rule-card">
            <div class="rule-number">02</div>
            <h3 class="rule-title">Respect the Undertone Harmony</h3>
            <p class="rule-desc">You can effortlessly blend 3 or more wood species as long as their baseline undertones align:</p>
            <ul class="rule-points">
              <li><strong>Warm Undertones:</strong> Red oak, teak, cherry, and honey pine mix smoothly together.</li>
              <li><strong>Cool Undertones:</strong> Weathered ash, walnut, and cerused rift oak sing together.</li>
              <li><strong>Bridge Elements:</strong> Jute, linen, or brass hardware seamlessly link divergent woods.</li>
            </ul>
          </div>

          <div class="rule-card">
            <div class="rule-number">03</div>
            <h3 class="rule-title">Biophilic Contrast Layering</h3>
            <p class="rule-desc">Wood is rigid and organic; pair it with contrasting physical mediums to accentuate its warmth:</p>
            <ul class="rule-points">
              <li><strong>Softness:</strong> Uncut velvet, washed Belgian linen, and boucle sheepskin.</li>
              <li><strong>Hard Cold Surfaces:</strong> Honed Carrara marble, matte cast iron, and smoked glass.</li>
              <li><strong>Living Flora:</strong> Large leaf fiddle-leaf figs, olive branches, and dried pampas.</li>
            </ul>
          </div>

          <div class="rule-card">
            <div class="rule-number">04</div>
            <h3 class="rule-title">Embrace Wabi-Sabi Patina</h3>
            <p class="rule-desc">Wood lives and breathes with your household. Perfection is the enemy of genuine warmth:</p>
            <ul class="rule-points">
              <li><strong>Character Marks:</strong> Gentle grain checking and knots add authenticity.</li>
              <li><strong>UV Sunlight Maturation:</strong> Cherry deepens with sun; walnut lightens to warm amber.</li>
              <li><strong>Heirloom Value:</strong> Small dents on an oil-finished table can be lifted with steam.</li>
            </ul>
          </div>

