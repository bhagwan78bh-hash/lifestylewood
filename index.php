          <div class="care-step-card">
            <div class="step-badge">Step 1</div>
            <h3>Daily & Weekly Dusting</h3>
            <p>Never use aerosol chemical sprays or synthetic silicone polishes which create gummy film buildup over time.</p>
            <div class="care-checklist">
              <span>✔ Use dry electrostatic microfiber</span>
              <span>✔ Wipe gently along the grain</span>
              <span>✔ Dampen with distilled water only for spills</span>
