        <div class="section-header text-center">
          <span class="section-tag">Common Inquiries</span>
          <h2 class="section-title">Frequently Asked Questions</h2>
          <p class="section-subtitle">Practical solutions to the most common wooden decor dilemmas.</p>
        </div>

        <div class="faq-list">
          <details class="faq-item" open>
            <summary class="faq-question">
              <span>Can I mix light and dark wood tones in the same room?</span>
              <span class="faq-icon" aria-hidden="true">+</span>
            </summary>
            <div class="faq-answer">
              <p>Absolutely. In fact, professional interior stylists discourage matching all wood items because it feels sterile and uninspired. The secret is ensuring the pieces share either a common undertone (warm vs cool) or repeating the accent tone at least twice (for example, a dark walnut coffee table balanced with a dark walnut picture frame and console lamp).</p>
            </div>
          </details>

          <details class="faq-item">
            <summary class="faq-question">
              <span>How do I protect wooden decor from direct sunlight fading?</span>
              <span class="faq-icon" aria-hidden="true">+</span>
            </summary>
            <div class="faq-answer">
              <p>Direct UV rays will slowly oxidize lignin in timber. While some woods like walnut naturally lighten and cherry deepens into rich amber, you can minimize uneven fading by rotating decor objects every three months, installing UV-filtering window films (which block 99% of rays without dimming light), and applying hard-wax oils containing built-in UV blockers.</p>
            </div>
          </details>

          <details class="faq-item">
            <summary class="faq-question">
              <span>What is the difference between solid hardwood and engineered veneer?</span>
              <span class="faq-icon" aria-hidden="true">+</span>
            </summary>
            <div class="faq-answer">
              <p>Solid hardwood consists of continuous lumber cut directly from a log. It can be sanded down, planed, and re-stained countless times over centuries. Wood veneer consists of a thin sheet of genuine timber bonded to an engineered plywood core; while structurally stable against humidity warping, it has a limited lifespan because it can only be sanded once or twice before exposing the substrate.</p>
            </div>
          </details>

          <details class="faq-item">
            <summary class="faq-question">
              <span>Can solid wooden decor be placed in high-moisture bathrooms?</span>
              <span class="faq-icon" aria-hidden="true">+</span>
            </summary>
            <div class="faq-answer">
              <p>Yes, provided you choose high-silica, naturally oily species like plantation teak, cedar, or hinoki cypress. Ensure the items are elevated off standing puddles and treated with water-resistant marine oils or penetrating hard-wax. Avoid open-pore oak or porous pine in direct shower steam zones.</p>
            </div>
          </details>
        </div>
      </div>
